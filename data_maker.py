with open("300.csv", "w") as f:
    for i in range(300):
        row = [
            f"{(i + 1) * 0.1 + 0 * 0.017:.3f}",
            f"{(i + 1) * 0.1 + 1 * 0.017:.3f}",
            f"{(i + 1) * 0.1 + 2 * 0.017:.3f}",
            f"{(i + 1) * 0.1 + 3 * 0.017:.3f}",
            f"{(i + 1) * 0.1 + 4 * 0.017:.3f}",
        ]
        f.write(",".join(row) + "\n")